function posterFallback(img, title) {
    if (!img) return;
    img.onerror = null;
    const txt = String(title || 'Nobre+')
        .replace(/&/g, '&amp;').replace(/</g, '&lt;')
        .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
    const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="300" height="450" viewBox="0 0 300 450">'
        + '<rect width="300" height="450" fill="#0B0C10"/>'
        + '<rect x="8" y="8" width="284" height="434" fill="none" stroke="rgba(212,175,55,0.4)" stroke-width="2"/>'
        + '<text x="150" y="208" text-anchor="middle" font-family="Montserrat, sans-serif" font-size="34" font-weight="800" fill="#D4AF37">Nobre+</text>'
        + '<text x="150" y="252" text-anchor="middle" font-family="Manrope, sans-serif" font-size="16" fill="#E6C670">' + txt + '</text>'
        + '<text x="150" y="424" text-anchor="middle" font-family="Montserrat, sans-serif" font-size="12" fill="#A1A4B2">Poster indisponível</text>'
        + '</svg>';
    img.src = 'data:image/svg+xml;charset=utf8,' + encodeURIComponent(svg);
}


